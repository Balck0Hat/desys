import { cssVar, resolveSurfaces } from '../tokens.js';

const declarations = (surfaces, colors) =>
  Object.entries(resolveSurfaces(surfaces, colors))
    .map(([key, value]) => `  ${cssVar(key)}: ${value};`)
    .join('\n');

const fontImport = (fonts) =>
  fonts.google
    ? `@import url('https://fonts.googleapis.com/css2?family=${fonts.google}&display=swap');\n\n`
    : '';

/**
 * CSS custom properties for light and dark surfaces, plus a couple of
 * base rules (background, text colour, font smoothing).
 * Works with Tailwind v3 and v4, or with no Tailwind at all.
 */
export const renderThemeCss = (tokens) => {
  const { surfaces, colors, fonts, name } = tokens;
  const dark = declarations(surfaces.dark, colors);
  return [
    `/* Generated by desys from systems/${name}/tokens.json. Do not edit by hand. */`,
    fontImport(fonts).trimEnd(),
    ':root {',
    declarations(surfaces.light, colors),
    '  color-scheme: light;',
    '}',
    '',
    '.dark,',
    '[data-theme="dark"] {',
    dark,
    '  color-scheme: dark;',
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    '  :root:not(.light):not([data-theme="light"]) {',
    dark.replace(/^/gm, '  '),
    '    color-scheme: dark;',
    '  }',
    '}',
    '',
    'body {',
    `  background-color: var(${cssVar('surface')});`,
    `  color: var(${cssVar('fg')});`,
    `  font-family: ${fonts.sans.map((f) => (f.includes(' ') ? `"${f}"` : f)).join(', ')};`,
    '  -webkit-font-smoothing: antialiased;',
    '}',
    '',
    '@media (prefers-reduced-motion: reduce) {',
    '  *, *::before, *::after {',
    '    animation-duration: 0.01ms !important;',
    '    transition-duration: 0.01ms !important;',
    '  }',
    '}',
    '',
  ]
    .join('\n')
    .replace(/\n{3,}/g, '\n\n');
};
