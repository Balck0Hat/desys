import { cssVar } from '../tokens.js';

const indent = (depth) => '  '.repeat(depth);

const renderValue = (value, depth) => {
  if (Array.isArray(value)) {
    return `[${value.map((item) => renderValue(item, depth)).join(', ')}]`;
  }
  if (typeof value === 'object' && value !== null) return renderObject(value, depth + 1);
  return JSON.stringify(value).replace(/"/g, "'");
};

const renderObject = (obj, depth = 1) => {
  const lines = Object.entries(obj).map(([key, value]) => {
    const safeKey = /^[a-zA-Z_$][\w$]*$/.test(key) ? key : `'${key}'`;
    return `${indent(depth)}${safeKey}: ${renderValue(value, depth)},`;
  });
  return `{\n${lines.join('\n')}\n${indent(depth - 1)}}`;
};

/** Surface tokens become CSS variables so dark mode can swap them. */
const surfaceColors = (surfaces) =>
  Object.fromEntries(Object.keys(surfaces.light).map((key) => [key, `var(${cssVar(key)})`]));

/** Brand scales get a DEFAULT so `bg-primary` / `text-primary` work. */
const withDefaults = (colors) =>
  Object.fromEntries(
    Object.entries(colors).map(([name, scale]) => [name, { DEFAULT: scale['600'], ...scale }]),
  );

/**
 * Render a Tailwind v3 preset for a token set.
 * Usage in a project: `presets: [require('./design-system/tailwind.preset.cjs')]`
 */
export const renderPreset = (tokens) => {
  const theme = {
    colors: { ...withDefaults(tokens.colors), ...surfaceColors(tokens.surfaces) },
    fontFamily: {
      sans: tokens.fonts.sans,
      display: tokens.fonts.display ?? tokens.fonts.sans,
    },
    borderRadius: tokens.radius,
    boxShadow: tokens.shadows,
    zIndex: tokens.zIndex,
    maxWidth: {
      container: tokens.layout?.container ?? '1280px',
      prose: tokens.layout?.prose ?? '65ch',
    },
    transitionDuration: {
      fast: tokens.motion?.fast ?? '150ms',
      DEFAULT: tokens.motion?.base ?? '200ms',
      slow: tokens.motion?.slow ?? '300ms',
    },
    transitionTimingFunction: {
      out: tokens.motion?.easeOut ?? 'cubic-bezier(0.16, 1, 0.3, 1)',
      in: tokens.motion?.easeIn ?? 'cubic-bezier(0.7, 0, 0.84, 0)',
    },
  };

  return [
    `/* Generated by desys from systems/${tokens.name}/tokens.json. Do not edit by hand. */`,
    `/* Re-run \`desys use ${tokens.name}\` to regenerate. */`,
    'module.exports = {',
    "  darkMode: ['class', '[data-theme=\"dark\"]'],",
    `  theme: { extend: ${renderObject(theme, 2)} },`,
    '};',
    '',
  ].join('\n');
};
