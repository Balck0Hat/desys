import { cssVar } from '../tokens.js';
import { renderThemeCss } from './themeCss.js';

const quoteFont = (font) => (font.includes(' ') ? `"${font}"` : font);

const scaleVars = (colors) =>
  Object.entries(colors).flatMap(([name, scale]) => [
    `  --color-${name}: ${scale['600']};`,
    ...Object.entries(scale).map(([step, hex]) => `  --color-${name}-${step}: ${hex};`),
  ]);

const simpleVars = (prefix, map = {}) =>
  Object.entries(map).map(([key, value]) => `  --${prefix}-${key}: ${value};`);

/**
 * Tailwind v4 entry file: `@import "tailwindcss"` + `@theme` with every token,
 * then the light/dark surface variables from themeCss.
 * Usage: replace your app's main CSS import with this file.
 */
export const renderV4Css = (tokens) => {
  const { colors, fonts, radius, shadows, zIndex, surfaces, motion = {} } = tokens;
  const inlineSurfaces = Object.keys(surfaces.light).map(
    (key) => `  --color-${key}: var(${cssVar(key)});`,
  );

  const theme = [
    '@theme {',
    ...scaleVars(colors),
    `  --font-sans: ${fonts.sans.map(quoteFont).join(', ')};`,
    `  --font-display: ${(fonts.display ?? fonts.sans).map(quoteFont).join(', ')};`,
    ...simpleVars('radius', radius),
    ...simpleVars('shadow', shadows),
    ...simpleVars('z', zIndex),
    `  --ease-out: ${motion.easeOut ?? 'cubic-bezier(0.16, 1, 0.3, 1)'};`,
    `  --ease-in: ${motion.easeIn ?? 'cubic-bezier(0.7, 0, 0.84, 0)'};`,
    '}',
    '',
    '@theme inline {',
    ...inlineSurfaces,
    '}',
  ].join('\n');

  const base = renderThemeCss(tokens).replace(/^\/\*.*\*\/\n/, '');

  return [
    `/* Generated by desys from systems/${tokens.name}/tokens.json. Do not edit by hand. */`,
    '@import "tailwindcss";',
    '',
    '@custom-variant dark (&:where(.dark, .dark *, [data-theme="dark"], [data-theme="dark"] *));',
    '',
    theme,
    '',
    base,
  ].join('\n');
};
